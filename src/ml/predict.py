MEDICAL_DISCLAIMER = (
    "EDUCATIONAL DISCLAIMER: This risk assessment is generated by a statistical machine learning "
    "model for educational and portfolio demonstration purposes. It does NOT constitute a clinical diagnosis, "
    "medical evaluation, or treatment plan. Individuals should always consult a licensed medical professional "
    "for proper diagnostic testing and health advice."
)


class PatientInputSchema(BaseModel):
    """Pydantic schema enforcing clinical validation boundaries on incoming patient parameters."""
    gender: str = Field(..., description="Gender (Female, Male, Other)")
    age: float = Field(..., ge=0.0, le=120.0, description="Age in years (0 - 120)")
    hypertension: int = Field(..., ge=0, le=1, description="Hypertension history (0: No, 1: Yes)")
    heart_disease: int = Field(..., ge=0, le=1, description="Heart disease history (0: No, 1: Yes)")
    smoking_history: str = Field(..., description="Smoking status (never, current, former, ever, not current, No Info)")
    bmi: float = Field(..., ge=10.0, le=100.0, description="Body Mass Index in kg/m² (10.0 - 100.0)")
    HbA1c_level: float = Field(..., ge=3.0, le=20.0, description="HbA1c blood percentage (3.0% - 20.0%)")
    blood_glucose_level: float = Field(..., ge=50.0, le=500.0, description="Blood glucose level in mg/dL (50 - 500)")

    @field_validator("gender")
    @classmethod
    def validate_gender(cls, v: str) -> str:
        valid_genders = {"Female", "Male", "Other"}
        cleaned = v.strip().capitalize()
        if cleaned not in valid_genders:
            raise ValueError(f"Invalid gender '{v}'. Must be one of {valid_genders}")
        return cleaned

    @field_validator("smoking_history")
    @classmethod
    def validate_smoking(cls, v: str) -> str:
        valid_history = {"never", "no info", "current", "former", "ever", "not current"}
        cleaned = v.strip().lower()
        if cleaned == "no info":
            return "No Info"
        if cleaned not in valid_history:
            return "No Info"
        return cleaned


class DiabetesPredictor:
    """
    Inference service encapsulating the fitted Scikit-Learn pipeline.
    Loads models/diabetes_pipeline.joblib and delivers calibrated risk scores.
    """
    def __init__(self, model_path: Path = MODEL_PIPELINE_PATH):
        self.model_path = model_path
        self.pipeline = None
        self._load_pipeline()

    def _load_pipeline(self) -> None:
        """Loads serialized model pipeline from disk."""
        if not self.model_path.exists():
            raise FileNotFoundError(
                f"Trained model pipeline not found at {self.model_path.resolve()}.\n"
                f"Please train the model first by running: python -m src.ml.train"
            )
        try:
            self.pipeline = joblib.load(self.model_path)
            logger.info(f"Loaded trained pipeline from {self.model_path}")
        except Exception as e:
            raise RuntimeError(f"Failed to deserialize pipeline at {self.model_path}: {e}")

    def predict_single(self, patient_data: Union[Dict[str, Any], PatientInputSchema]) -> Dict[str, Any]:
        """
        Generates risk prediction for an individual patient.
        
        Args:
            patient_data: Dict or PatientInputSchema containing patient biometrics.
            
        Returns:
            dict: Structured prediction response with risk category and probability.
        """
        # Validate through Pydantic
        if isinstance(patient_data, dict):
            validated = PatientInputSchema(**patient_data)
        else:
            validated = patient_data

        input_df = pd.DataFrame([validated.model_dump()])

        # Generate prediction and probabilities
        pred_class = int(self.pipeline.predict(input_df)[0])
        probabilities = self.pipeline.predict_proba(input_df)[0]
        prob_diabetic = float(probabilities[1])

        # Risk Stratification based on clinical probability thresholds
        if prob_diabetic < 0.30:
            risk_tier = "Low Risk"
            risk_color = "#28a745" # Green
            clinical_advice = "Patient indicators are within normal screening ranges. Maintain healthy lifestyle."
        elif prob_diabetic < 0.60:
            risk_tier = "Moderate Risk"
            risk_color = "#ffc107" # Amber
            clinical_advice = "Borderline biomarker indicators observed. Recommend confirmatory FPG/HbA1c clinical testing."
        else:
            risk_tier = "High Risk"
            risk_color = "#dc3545" # Red
            clinical_advice = "Elevated risk profile detected. Urgent clinical consultation and laboratory diagnostic workup advised."

        return {
            "prediction_class": pred_class,
            "prediction_label": "Diabetic Risk Detected" if pred_class == 1 else "Non-Diabetic",
            "risk_tier": risk_tier,
            "risk_color": risk_color,
            "probability_diabetic": round(prob_diabetic, 4),
            "probability_percentage": round(prob_diabetic * 100, 2),
            "clinical_recommendation": clinical_advice,
            "patient_inputs": validated.model_dump(),
            "disclaimer": MEDICAL_DISCLAIMER
        }

    def predict_batch(self, df: pd.DataFrame) -> pd.DataFrame:
        """
        Performs batch prediction on a dataframe of patient records.
        
        Args:
            df: DataFrame containing raw patient features.
            
        Returns:
            pd.DataFrame: Original DataFrame augmented with prediction and probability columns.
        """
        result_df = df.copy()
        result_df["predicted_class"] = self.pipeline.predict(df)
        result_df["diabetes_probability"] = self.pipeline.predict_proba(df)[:, 1]
        result_df["risk_tier"] = pd.cut(
            result_df["diabetes_probability"],
            bins=[-np.inf, 0.30, 0.60, np.inf],
            labels=["Low Risk", "Moderate Risk", "High Risk"]
        )
        return result_df


